function model_samples(R)
    s := R.1;
    t := R.2;
    p := Characteristic(R);
    if p eq 2 then
        samples := [
            <2^30+2^28+2^22, [R | s*t, 0, s^6+t^6, 0, 0]>,
            <2^31+2^12, [R | s^2, 0, 0, 0, s^12]>,
            <2^20+2^14, [R | 0, 0, 0, s^7*t+s*t^7, 0]>,
            <2, [R | 0, 0, 0, 0, s*t^11]>,
            <2^30+2^27+2^23+2^21+2^13,
                [R | s*t, 0, s^5*t+s*t^5, s^8+t^8, 0]>,
            <0, [R | 0, 0, 0, 0, 0]>];
    else
        samples := [
            <3^25+3^23+3^21+3^13,
                [R | 0, s^3*t+s*t^3, 0, s^8+t^8, 0]>,
            <3^26+3^12, [R | 0, s^4, 0, 0, s^12]>,
            <3^11+3, [R | 0, 0, 0, 0, s^11*t+s*t^11]>,
            <3, [R | 0, 0, 0, 0, s*t^11]>,
            <3^25+3^23, [R | 0, s^3*t+s*t^3, 0, 0, 0]>,
            <0, [R | 0, 0, 0, 0, 0]>];
    end if;
    return samples;
end function;
